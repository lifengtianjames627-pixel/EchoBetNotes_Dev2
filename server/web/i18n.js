export function normalizeLang(value) {
  const code = String(value || '').trim().toLowerCase().slice(0, 2);
  return SUPPORTED.has(code) ? code : 'en';
}

export function langFromRequest(request) {
  if (request.query?.lang) return normalizeLang(request.query.lang);
  if (request.cookies?.lang) return normalizeLang(request.cookies.lang);
  const accept = String(request.headers['accept-language'] || '').split(',')[0];
  return normalizeLang(accept);
}

export function t(lang, key) {
  const code = normalizeLang(lang);
  return TRANSLATIONS[code]?.[key] || TRANSLATIONS.en[key] || key;
}
